import fs from 'node:fs';

const vendor = fs.readFileSync(new URL('../platform/cpp/vendor/md4c/entity.c', import.meta.url), 'utf8');
const license = vendor.slice(0, vendor.indexOf('*/') + 2);
const entries = [...vendor.matchAll(/\{ "&([^";]+);", \{ (\d+), (\d+) \} \}/g)];
if (entries.length < 2000) throw new Error('Could not read the md4c entity table');
const rows = entries.map(([, name, first, second]) => {
  const points = Number(second) === 0 ? [Number(first)] : [Number(first), Number(second)];
  return `  ${JSON.stringify(name)}: ${JSON.stringify(String.fromCodePoint(...points))},`;
});
fs.writeFileSync(new URL('../src/engine/namedEntities.ts', import.meta.url),
  `${license}\n\n// Generated by scripts/generate-entities.mjs from the bundled md4c table.\n` +
  `export const NAMED_ENTITIES: Readonly<Record<string, string>> = Object.freeze({\n${rows.join('\n')}\n});\n`);
